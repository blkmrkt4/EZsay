/**
 * Returns preference definitions filtered for a given document type.
 */
export function getDefinitionsForDocType(documentType: string | null): PreferenceDefinition[] {
  if (!documentType) return PREFERENCE_DEFINITIONS.filter((d) => d.documentTypes.includes("all"));
  return PREFERENCE_DEFINITIONS.filter(
    (d) => d.documentTypes.includes("all") || d.documentTypes.includes(documentType),
  );
}

/**
 * Returns the default value map for a given document type.
 */
export function getDefaultPreferences(documentType: string | null): Record<string, string | boolean | number> {
  const defs = getDefinitionsForDocType(documentType);
  const defaults: Record<string, string | boolean | number> = {};
  for (const d of defs) defaults[d.key] = d.defaultValue;
  return defaults;
}
