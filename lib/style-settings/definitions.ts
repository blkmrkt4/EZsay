/**
 * Style preference definitions — single source of truth for the wizard and settings panel.
 * Each entry describes one configurable style rule: its UI, default, and how it affects scanning.
 */

export type PreferenceCategory = "universal" | "academic" | "legal" | "fiction" | "marketing" | "business" | "strictness" | "punctuation" | "numbers" | "capitalisation" | "formatting";

export interface PreferenceDefinition {
  key: string;
  label: string;
  description: string;
  category: PreferenceCategory;
  inputType: "select" | "boolean" | "number" | "text";
  options?: { value: string; label: string }[];
  defaultValue: string | boolean | number;
  /** Which document types this preference applies to. ["all"] means always visible. */
  documentTypes: string[];
  /** If true, this setting is hidden behind "Advanced options" toggle. */
  advanced?: boolean;
  /** If set, this preference appears in the wizard at the given step. */
  wizardStep?: number;
  wizardPriority?: number;
  scanEffect?: {
    type: "prompt_token" | "library_toggle" | "threshold";
    /** For prompt_token: the [BRACKET] key injected into prompts. */
    tokenKey?: string;
    /** For library_toggle/threshold: which semantic pattern or library category. */
    ruleId?: string;
  };
}

